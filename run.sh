#!/bin/bash
# ==============================================
# run.sh — запуск Yolov5_RK3588 WebUI с камерой
# ==============================================

# ------------------------------------------------
# 1. Путь к папке скрипта
DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd )"

# ------------------------------------------------
# 2. Проверка активного conda окружения
if [[ -z "$CONDA_PREFIX" ]]; then
    echo "Ошибка: активируйте conda-окружение rknn_yolo перед запуском"
    echo "Используйте: conda activate rknn_yolo"
    exit 1
fi

# ------------------------------------------------
# 3. Путь к python из активного окружения
PYTHON="$CONDA_PREFIX/bin/python3"

if [[ ! -f "$PYTHON" ]]; then
    echo "Ошибка: python3 не найден в активном окружении: $CONDA_PREFIX"
    exit 1
fi

# ------------------------------------------------
# 4. Запуск main.py с явным указанием источника камеры
#    camera_source=11 соответствует /dev/video11
#    Если main.py поддерживает флаги --source, --pixel-format и т.п., их можно добавить
$PYTHON "$DIR/main.py" --camera-source 11 --pixel-format MJPG

# ------------------------------------------------
# 5. Вывод информационного сообщения
echo "WebUI запущен. Сервер должен слушать порт 8080."
echo "Для просмотра потока на ПК: adb forward tcp:8080 tcp:8080"
echo "ffplay http://localhost:8080/frame"

